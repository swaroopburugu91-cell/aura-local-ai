"""
Aura Local AI - Direct Autonomous Laptop Interaction Engine
Executes commands, manipulates files, and controls Windows applications directly
without requiring manual user button clicks.
"""
import re
import os
from pathlib import Path
from typing import Dict, Any, Optional, Tuple
from app.tools import (
    execute_shell_command,
    list_folder_contents,
    read_laptop_file,
    write_laptop_file,
    launch_desktop_application,
    USER_HOME,
    DESKTOP_DIR
)

def handle_direct_system_intent(prompt: str) -> Optional[Dict[str, Any]]:
    """Detect and instantly execute direct Windows system intents with zero LLM lag."""
    p_lower = prompt.lower().strip()

    # 1. Direct App Launch Intents (e.g., "open notepad", "launch calculator", "open vs code")
    app_patterns = [
        r"(?:open|launch|start|run)\s+(notepad|calculator|calc|code|vs\s*code|vscode|explorer|files|chrome)",
    ]
    for pattern in app_patterns:
        m = re.search(pattern, p_lower)
        if m:
            raw_name = m.group(1).replace(" ", "")
            res = launch_desktop_application(raw_name)
            if res.get("success"):
                return {
                    "action_type": "app_launch",
                    "target": raw_name,
                    "message": f"**[Direct Laptop Action Executed]** Launched **{raw_name.upper()}** on your Windows laptop."
                }

    # 2. Direct Folder Listing Intents (e.g., "show my desktop", "list downloads", "what is on my desktop")
    if any(k in p_lower for k in ["desktop", "downloads", "documents"]) and any(v in p_lower for v in ["show", "list", "view", "see", "check", "files", "open", "what"]):
        folder_match = re.search(r"(desktop|downloads|documents)", p_lower)
        if folder_match:
            folder_name = folder_match.group(1).capitalize()
            res = list_folder_contents(folder_name)
            if res.get("success"):
                items = res.get("items", [])[:20]
                item_lines = []
                for it in items:
                    icon = "[DIR]" if it["is_directory"] else "[FILE]"
                    item_lines.append(f"- {icon} `{it['name']}` ({it['size_readable']})")
                items_str = "\n".join(item_lines) if item_lines else "_Folder is currently empty._"
                return {
                    "action_type": "list_files",
                    "target": folder_name,
                    "message": f"**[Direct Laptop Action Executed]** Inspected `{folder_name}` folder ({len(items)} items found):\n\n{items_str}"
                }

    # 3. Direct Folder Creation on Desktop
    if "folder" in p_lower and ("create" in p_lower or "make" in p_lower):
        m = re.search(r"(?:called|named)?\s+[\"']?([a-zA-Z0-9_\-]+)[\"']?", p_lower)
        target_name = m.group(1).strip() if m else "NewFolder"
        target_dir = DESKTOP_DIR / target_name
        try:
            target_dir.mkdir(parents=True, exist_ok=True)
            return {
                "action_type": "create_folder",
                "target": str(target_dir),
                "message": f"**[Direct Laptop Action Executed]** Created folder on your Windows Desktop:\n`{target_dir}`"
            }
        except Exception as e:
            return {
                "action_type": "create_folder",
                "target": str(target_dir),
                "message": f"Failed to create folder: {str(e)}"
            }

    # 4. Direct Command Execution (e.g. "run command: dir", "execute: ipconfig", "powershell: Get-Date")
    cmd_match = re.search(r"^(?:run|execute|exec|powershell|cmd):\s*(.+)$", prompt, re.IGNORECASE)
    if cmd_match:
        cmd_str = cmd_match.group(1).strip()
        res = execute_shell_command(cmd_str)
        out = res.get("stdout") or res.get("stderr") or "Command executed successfully (no output)."
        return {
            "action_type": "execute_command",
            "target": cmd_str,
            "message": f"**[Direct Laptop Action Executed]** Running `{cmd_str}`\n\n```powershell\n{out}\n```"
        }

    return None

def execute_action_tag(text: str) -> Tuple[str, Optional[Dict[str, Any]]]:
    """
    Search for action tags generated by the LLM:
    <<<ACTION:execute_command:Get-Date>>>
    <<<ACTION:launch_app:notepad>>>
    <<<ACTION:write_file:path|content>>>
    Execute them directly and replace with the real execution output.
    """
    action_match = re.search(r"<<<ACTION:([a-zA-Z0-9_]+):([\s\S]*?)>>>", text)
    if not action_match:
        return text, None

    action_type = action_match.group(1).strip()
    action_arg = action_match.group(2).strip()
    result_text = ""

    if action_type == "execute_command":
        res = execute_shell_command(action_arg)
        output = res.get("stdout") or res.get("stderr") or "Command completed with code 0."
        result_text = f"\n\n**[Executed on Laptop]** `{action_arg}`:\n```\n{output}\n```\n"

    elif action_type == "launch_app":
        res = launch_desktop_application(action_arg)
        result_text = f"\n\n**[Launched Desktop App]** `{action_arg}`\n"

    elif action_type == "write_file":
        parts = action_arg.split("|", 1)
        if len(parts) == 2:
            path_str, content_str = parts[0].strip(), parts[1].strip()
            res = write_laptop_file(path_str, content_str)
            if res.get("success"):
                result_text = f"\n\n**[File Created on Laptop]** `{res.get('path')}` ({res.get('bytes_written')} bytes)\n"
            else:
                result_text = f"\n\n**[File Creation Failed]** {res.get('error')}\n"

    cleaned_text = text[:action_match.start()] + result_text + text[action_match.end():]
    return cleaned_text, {"type": action_type, "arg": action_arg}
